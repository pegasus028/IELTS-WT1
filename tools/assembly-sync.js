/* WS-B · Assembly v2 — content sync.
   Copies the WS-D content bank into the app:
     out/WS-D/content/vw2-games.json  →  assembly-content.js  (ES5, window.ASSEMBLY_CONTENT)
     out/WS-D/content/vw2-prompts.js  →  vw2-prompts.js       (ES5, pushes onto window.CONTENT.PROMPTS)
   and writes the fixed Assembly teams (Groups tab of the lesson-plan workbook, 23 Oct 2026)
   mapped to roster.js ids.

   node tools/assembly-sync.js [path/to/WS-D/content]
   The default source is /home/claude/vw2/out/WS-D/content. Re-run whenever WS-D changes a set;
   then bump ?v= on assembly-content.js and vw2-prompts.js in index.html and teacher.html.   */
'use strict';
var fs = require('fs'), path = require('path'), vm = require('vm');
var ROOT = path.join(__dirname, '..');
var SRC = process.argv[2] || '/home/claude/vw2/out/WS-D/content';

/* Groups tab, 23 Oct 2026. Nicknames as T.Chris wrote them; ids resolved against roster.js.
   WS-I (23 Oct): WS-G's roster keeps Airin on her existing id m41-ai, Lilil on m41-lillil, and adds
   m41-donut for the M4.1 Donut (tut-donut is the tutee's separate account; never merge them). */
var TEAMS = [
  { n: 1, name: 'Team 1', members: ['Donut', 'Lookchin', 'Baiplu', 'Sun', 'Mint'] },
  { n: 2, name: 'Team 2', members: ['Proud', 'Airin', 'Oly', 'Noyny', 'Ob-oon'] },
  { n: 3, name: 'Team 3', members: ['Pasta', 'Premier', 'Nicha', 'Nene', 'Punnee'] },
  { n: 4, name: 'Team 4', members: ['Vernier', 'Rak', 'Min', 'Panghom', 'Carrot'] },
  { n: 5, name: 'Team 5', members: ['Chicha', 'Wongree', 'Moquette', 'Pin', 'Lilil'] },
  { n: 6, name: 'Team 6', members: ['Thinn', 'Ren', 'Khaofang', 'Gam', 'Mon'] }
];
var ALIAS = { airin: 'm41-ai', lilil: 'm41-lillil', donut: 'm41-donut' };

var ctx = { window: {} }; ctx.window.window = ctx.window; vm.createContext(ctx);
vm.runInContext(fs.readFileSync(path.join(ROOT, 'roster.js'), 'utf8'), ctx);
var roster = ctx.ROSTER || ctx.window.ROSTER || [];
var byName = {}; roster.forEach(function (r) { byName[String(r.name).toLowerCase()] = r.id; });
var unmatched = [];
TEAMS.forEach(function (t) {
  t.ids = t.members.map(function (nm) {
    var k = nm.toLowerCase(), id = ALIAS[k] || byName[k];
    if (!id) { id = 'm41-' + k.replace(/[^a-z0-9]/g, ''); unmatched.push(nm + ' → ' + id + ' (not in roster.js)'); }
    return id;
  });
});

var games = JSON.parse(fs.readFileSync(path.join(SRC, 'vw2-games.json'), 'utf8'));
var promptsSrc = fs.readFileSync(path.join(SRC, 'vw2-prompts.js'), 'utf8');
/* ES5 guard on the prompts file before it enters the repo */
var stripped = promptsSrc.replace(/'[^'\n]*'|"[^"\n]*"/g, "''");
if (/=>|`/.test(stripped) || /(^|[;{}\s])(let|const)\s+[A-Za-z_$]/m.test(stripped)) throw new Error('vw2-prompts.js is not ES5');

var out = '/* ===========================================================================\n' +
  '   QUILLMOOR ACADEMY · THE OBSERVATORY — assembly-content.js  (WS-B, generated)\n' +
  '   GENERATED by tools/assembly-sync.js from WS-D\'s vw2-games.json (version ' + games.version + ').\n' +
  '   Do not edit by hand: change the JSON (or the TEAMS table in the tool) and re-run the tool.\n' +
  '   window.ASSEMBLY_CONTENT = { version, games: { <gameId>: {…} }, teams: [ { n, name, members, ids } ] }\n' +
  '   Game shapes (A-tabs of the lesson plan): mode-sort cards[12] (choice) · paraphrase-relay rounds[3] (post) ·\n' +
  '   overview-or-not cards[12] (judge = choice of five labels) · number-hunt (post-datacheck) · group-them (post) ·\n' +
  '   twice-as-much rounds[2] (bid) · slice-it / table-detective (post-datacheck) · examiners-chair scripts[2] (checklist) ·\n' +
  '   data-dictation (paper; listed for the slides, no round). Prompt ids p-vw2-* come from vw2-prompts.js.\n' +
  '   =========================================================================== */\n' +
  'window.ASSEMBLY_CONTENT = ' + JSON.stringify({ version: games.version, games: games.games, teams: TEAMS }, null, 1).replace(/\u2028|\u2029/g, '') + ';\n';
fs.writeFileSync(path.join(ROOT, 'assembly-content.js'), out);
fs.writeFileSync(path.join(ROOT, 'vw2-prompts.js'), promptsSrc);
console.log('assembly-content.js: ' + Object.keys(games.games).length + ' games, version ' + games.version + '; vw2-prompts.js copied (' + (promptsSrc.match(/P\.push/g) || []).length + ' prompts).');
if (unmatched.length) console.log('Team members not in roster.js (ids guessed): ' + unmatched.join('; '));
