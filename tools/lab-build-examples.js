/* Builds lab-examples.js (the Workshop's Examples tab) from examples-t1/*.json.
   Lines are written with [Slot Label]s in the JSON and stored with {key}
   tokens. Run tools/lab-validate.js afterwards: it checks every example's
   figures against its chart and runs the Ten Wards on every report.
   node tools/lab-build-examples.js                                          */
'use strict';
const fs = require('fs'), path = require('path'), vm = require('vm');
const ROOT = path.join(__dirname, '..'), DIR = path.join(ROOT, 'examples-t1');
const ctx = { window: {} }; ctx.window.window = ctx.window; vm.createContext(ctx);
vm.runInContext(fs.readFileSync(path.join(ROOT, 'lab-content.js'), 'utf8'), ctx);
const L = ctx.window.LabContent;

const head = JSON.parse(fs.readFileSync(path.join(DIR, 'students.json'), 'utf8'));
const order = { nam: 0, fah: 1 }, modeOrder = L.MODE_ORDER;
const sets = fs.readdirSync(DIR).filter(function (f) { return /^(nam|fah)-[a-z]+\.json$/.test(f); }).map(function (f) {
  const ex = JSON.parse(fs.readFileSync(path.join(DIR, f), 'utf8')), M = L.MODES[ex.mode];
  if (!M) throw new Error(f + ': unknown mode ' + ex.mode);
  const lines = {};
  M.lines.forEach(function (c) {
    const raw = ex.lines[c.id];
    if (!raw) throw new Error(f + ': no line ' + c.id);
    lines[c.id] = raw.replace(/\[([^\]]+)\]/g, function (m, name) {
      const k = M.SLOT_ALIASES[name.trim().toLowerCase()];
      if (!k) throw new Error(f + ' ' + c.id + ': unknown slot [' + name + ']');
      return '{' + k + '}';
    });
  });
  return { id: ex.id, student: ex.student, mode: ex.mode, level: ex.level, pct: ex.pct, promptId: ex.promptId, lines: lines, vars: ex.vars, rating: ex.rating, coaching: ex.coaching || [] };
}).sort(function (a, b) { return (order[a.student] - order[b.student]) || (modeOrder.indexOf(a.mode) - modeOrder.indexOf(b.mode)); });

const out = '/* ===========================================================================\n' +
  '   QUILLMOOR ACADEMY · THE OBSERVATORY (Chart Control, Task 1) — lab-examples.js\n' +
  '   GENERATED by tools/lab-build-examples.js from examples-t1/*.json. Do not edit:\n' +
  '   change the JSON, rebuild, then run tools/lab-validate.js.\n' +
  '   Two AI-simulated students (Nam, B1, 60% pages; Fah, B2, 40% pages), one page\n' +
  '   per mode, each cast on one bank chart.\n' +
  '   =========================================================================== */\n' +
  'window.LabExamples = ' + JSON.stringify({ note: head.note, students: head.students, sets: sets }, null, 1) + ';\n';
fs.writeFileSync(path.join(ROOT, 'lab-examples.js'), out);
console.log('lab-examples.js: ' + sets.length + ' example sets (' + sets.map(function (s) { return s.id; }).join(', ') + ')');
